import { useState } from "react";
import { Navigate, useNavigate } from "react-router-dom";
import { AuthLayout } from "../auth/AuthLayout";
import { refreshSessionClaims } from "../auth/api";
import { useAuth } from "../auth/AuthProvider";
import { setUpHospital } from "./api";

/**
 * The first person in claims the install; everyone after them joins by
 * invite. There's one hospital per deployment, so this screen runs once
 * — and when it refuses, it's because someone else got here first, which
 * is a different thing from an error and is worth saying plainly.
 */
export function SetUpHospitalPage() {
  const navigate = useNavigate();
  const { role } = useAuth();
  const [name, setName] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [needsInvite, setNeedsInvite] = useState(false);

  // Already has an account (e.g. revisited this URL directly).
  if (role) return <Navigate to="/" replace />;

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    setError(null);
    setIsSubmitting(true);
    try {
      await setUpHospital(name);
      // The token in hand still carries no role — the Custom Access Token
      // hook only runs at mint/refresh time, not retroactively.
      await refreshSessionClaims();
      navigate("/onboarding/profile");
    } catch (err) {
      const message =
        err instanceof Error ? err.message : "Couldn't finish setting up.";
      // 409 from the API: somebody already claimed this install.
      if (message.includes("already set up")) {
        setNeedsInvite(true);
      } else {
        setError(message);
      }
      setIsSubmitting(false);
    }
  }

  if (needsInvite) {
    return (
      <AuthLayout
        heading="This ClaimFlow is already set up"
        subheading="Someone at your hospital got here first. Ask them for an invite link and you'll be added with the right role."
      >
        <p className="auth-footnote">
          Invite links are generated by an admin from Settings.
        </p>
      </AuthLayout>
    );
  }

  return (
    <AuthLayout
      heading="Set up your hospital"
      subheading="This name appears across ClaimFlow and on everything sent to a TPA."
    >
      <form onSubmit={handleSubmit}>
        {error ? <div className="inline-error">{error}</div> : null}
        <div className="form-field">
          <label htmlFor="name">Hospital name</label>
          <input
            id="name"
            type="text"
            required
            placeholder="e.g. City General Hospital"
            value={name}
            onChange={(e) => setName(e.target.value)}
          />
        </div>
        <button
          type="submit"
          className="btn btn--primary btn--full"
          disabled={isSubmitting}
        >
          {isSubmitting ? "Setting up…" : "Continue"}
        </button>
      </form>
    </AuthLayout>
  );
}
