import { Navigate, Outlet } from "react-router-dom";
import { useAuth } from "../features/auth/AuthProvider";
import { useMe } from "../features/auth/me";
import { AuthLayout } from "../features/auth/AuthLayout";
import { Loader } from "../components/ui/loader";
import { useHospital } from "../features/hospital/api";

export function RequireAuth() {
  const { session, loading } = useAuth();

  if (loading) return <Loader fullPage />;
  if (!session) return <Navigate to="/login" replace />;

  return <Outlet />;
}

/**
 * Past RequireAuth a session exists, but it may carry no role claim.
 *
 * A missing claim does NOT mean "no account". The claim is stamped by
 * Supabase's Custom Access Token hook when a token is minted, so a
 * membership created afterwards — accepting an invite in another tab,
 * an admin granting a role, a restored database — leaves the claim
 * absent while the row plainly exists. Treating that as "no account"
 * sent people to a setup screen that then refused them with "you
 * already have an account" and no way out.
 *
 * So the claim is the fast path and the server is the truth: if the
 * claim is missing, ask /me before concluding anything.
 *
 * There used to be a "set up your hospital" screen this sent people to.
 * It has no job left — there's one hospital per install, it already
 * exists, and that form could only ever end in "already set up, ask for
 * an invite" — so this just says that directly instead of bouncing
 * through a dead screen to reach the same message.
 */
export function RequireMembership() {
  const { role: claimedRole } = useAuth();
  // Only pay for the round trip when the fast path missed.
  const { data: me, isLoading, isError } = useMe(!claimedRole);

  if (claimedRole) return <Outlet />;
  if (isLoading) return <Loader fullPage />;
  if (!isError && me?.role) return <Outlet />;

  return (
    <AuthLayout
      heading="No account here yet"
      subheading={`${me?.hospitalName ?? "This hospital"} is already set up. Ask a colleague for an invite link and you'll be added with the right role.`}
    >
      <p className="mt-3 text-center text-sm text-ink-faint">
        Invite links are generated by an admin from Settings.
      </p>
    </AuthLayout>
  );
}

/**
 * A hospital can exist with a half-finished profile — a desk can't
 * actually file a cashless claim without a ROHINI id and the rest, so
 * the app holds everyone in the wizard until it's done. Only an admin
 * can complete it, so anyone else gets told who to ask rather than being
 * bounced into a form they'd be 403'd on.
 */
export function RequireCompleteProfile() {
  const { role } = useAuth();
  const { data: hospital, isLoading } = useHospital();

  if (isLoading) return <Loader fullPage />;
  if (!hospital || hospital.onboardingCompletedAt) return <Outlet />;

  if (role !== "org_admin") {
    return (
      <div className="flex min-h-screen items-center justify-center p-6">
        <div className="flex w-full max-w-[400px] flex-col gap-1">
          <h1 className="mb-1 text-center text-xl font-semibold tracking-[-0.01em]">
            Setup isn&apos;t finished
          </h1>
          <p className="mb-6 text-center text-base text-ink-faint">
            {hospital.name} still needs its registration details added before
            claims can be filed. Ask your admin to finish setting up.
          </p>
        </div>
      </div>
    );
  }

  return <Navigate to="/onboarding/profile" replace />;
}
